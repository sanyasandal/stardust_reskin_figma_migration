#!/usr/bin/env node
// Convert the captured source .plain.html (fortstreet-h.schools.nsw.gov.au is itself EDS) into DA
// HTML at content/<path>.html. Text is moved node-for-node (never rewritten); the structure is
// re-shaped per block-survey.md: one DA section per source wrapper, M1 hero lead on content pages,
// block renames (card-container → cards, accordions → accordion), embeds as plain links,
// images rehosted on DA media, section tones → `Style | light`, a metadata block from the head.
// Usage: node stardust/.work/deploy/convert-plain.mjs [--pages pages51.txt]
// Writes content/**.html and stardust/.work/deploy/media-manifest-siblings.json, convert-report.json.
import fs from 'node:fs';
import path from 'node:path';
import { chromium } from 'playwright';

const ROOT = process.cwd();
const WORK = path.join(ROOT, 'stardust/.work/deploy');
const HOST = 'https://fortstreet-h.schools.nsw.gov.au';
const DA_MEDIA = 'https://content.da.live/sanyasandal/stardust-reskin-figma-migration/media/fortstreet/';
const HUBS = ['/about-us', '/school-life', '/learning-and-support', '/our-community'];
const FACEBOOK = 'https://www.facebook.com/fortstreethighschool/';
const FACEBOOK_TEXT = 'Fort Street High School on Facebook';

const pagesArg = process.argv.indexOf('--pages');
const pagesFile = pagesArg > -1 ? process.argv[pagesArg + 1] : path.join(WORK, 'pages51.txt');
const pages = fs.readFileSync(pagesFile, 'utf8').split('\n').map((l) => l.trim()).filter(Boolean);

function slug(p) { return p.replace(/^\//, '').replace(/\//g, '~'); }

function headMeta(full) {
  const title = (full.match(/<title>([^<]*)<\/title>/) || [])[1] || '';
  const desc = (full.match(/<meta name="description" content="([^"]*)"/) || [])[1] || '';
  return { title, desc };
}

// Runs in the browser: returns { html, media, stats }.
function transform({
  plain, pagePath, isHub, meta, cfg,
}) {
  const doc = new DOMParser().parseFromString(`<body>${plain}</body>`, 'text/html');
  const body = doc.body;
  const stats = {
    droppedImages: 0, images: 0, demotedH1: [], blocks: [], ctaToColumns: 0, hero: false,
  };
  const media = [];
  const el = (tag, cls) => { const e = doc.createElement(tag); if (cls) e.className = cls; return e; };
  const isBlank = (n) => n.nodeType === 3 ? !n.textContent.trim() : n.nodeType === 8;

  // --- images: drop broken (about:error), rehost the rest on DA media as <picture><img>
  body.querySelectorAll('img').forEach((img) => {
    const src = img.getAttribute('src') || '';
    const pic = img.closest('picture') || img;
    if (src.startsWith('about:error') || !src) {
      const parent = pic.parentElement;
      pic.remove();
      stats.droppedImages += 1;
      if (parent && parent.tagName === 'P' && !parent.textContent.trim() && !parent.children.length) parent.remove();
      return;
    }
    const url = new URL(src, `${cfg.host}${pagePath}`);
    const name = url.pathname.split('/').pop();
    const format = url.searchParams.get('format') || name.split('.').pop();
    media.push({
      file: `stardust/.work/deploy/media/${name}`,
      source: `${cfg.host}/${name}?width=2000&format=${format === 'jpeg' ? 'jpg' : format}&optimize=medium`,
      name,
    });
    const picture = el('picture');
    const nimg = el('img');
    nimg.setAttribute('src', cfg.daMedia + name);
    nimg.setAttribute('alt', img.getAttribute('alt') || '');
    picture.append(nimg);
    pic.replaceWith(picture);
    stats.images += 1;
  });

  // --- links: absolute against the source host (localize-links makes internal ones root-relative)
  body.querySelectorAll('a[href]').forEach((a) => {
    const href = a.getAttribute('href');
    if (/^(mailto:|tel:|#)/.test(href)) return;
    try { a.setAttribute('href', new URL(href, `${cfg.host}${pagePath}`).href); } catch { /* keep */ }
  });

  // --- headings: ids are generated by the pipeline; one h1 per page
  body.querySelectorAll('h1,h2,h3,h4,h5,h6').forEach((h) => {
    h.removeAttribute('id');
    // a heading wrapped whole in <strong> (home precedent: the mark is redundant on a heading)
    const only = h.children.length === 1 && h.firstElementChild;
    if (only && only.tagName === 'STRONG' && h.textContent.trim() === only.textContent.trim()) {
      only.replaceWith(...only.childNodes);
      stats.headingStrongUnwrapped = (stats.headingStrongUnwrapped || 0) + 1;
    }
  });
  const h1s = [...body.querySelectorAll('h1')];
  h1s.forEach((h, i) => {
    if (!h.textContent.trim() && h.querySelector('picture')) {
      // careers: <h1 id=""><picture></h1> — an image, not a heading
      const p = el('p');
      p.append(...h.childNodes);
      h.replaceWith(p);
      stats.demotedH1.push('(picture-only h1 → p)');
      return;
    }
    if (i === 0 || h1s.slice(0, i).every((x) => !x.textContent.trim())) return;
    const h2 = el('h2');
    h2.append(...h.childNodes);
    h.replaceWith(h2);
    stats.demotedH1.push(h2.textContent.trim());
  });

  // --- sections
  const sections = [...body.children].filter((s) => s.tagName === 'DIV');
  const out = [];
  const pushSection = (nodes, style) => {
    const content = nodes.filter((n) => !isBlank(n));
    if (!content.length) return;
    out.push({ nodes: content, style });
  };

  const convertBlock = (block) => {
    const [name, ...variants] = [...block.classList];
    let newName = name;
    if (name === 'card-container') newName = 'cards';
    if (name === 'accordions') newName = 'accordion';
    stats.blocks.push(newName + (variants.length ? ` (${variants.join(', ')})` : ''));
    if (name === 'embed') {
      const a = block.querySelector('a[href]');
      const p = el('p');
      if (a) p.append(a);
      return p;
    }
    if (name === 'facebook-feed') {
      const b = el('div', 'facebook-feed');
      const row = el('div'); const cell = el('div'); const p = el('p'); const a = el('a');
      a.setAttribute('href', cfg.facebook); a.textContent = cfg.facebookText;
      p.append(a); cell.append(p); row.append(cell); b.append(row);
      return b;
    }
    if (name === 'accordions') {
      // the source renders accordion titles as button labels (live DOM has no heading there):
      // a title cell holding a single heading/paragraph is unwrapped to its inline content
      [...block.children].forEach((row) => {
        const title = row.firstElementChild;
        const only = title && title.children.length === 1 && title.firstElementChild;
        if (only && /^(H[1-6]|P)$/.test(only.tagName) && title.textContent.trim() === only.textContent.trim()) {
          only.replaceWith(...only.childNodes);
          stats.accordionTitlesUnwrapped = (stats.accordionTitlesUnwrapped || 0) + 1;
        }
      });
    }
    block.className = [newName, ...variants].join(' ');
    return block;
  };

  const isPictureOnly = (n) => n.nodeType === 1 && (n.tagName === 'PICTURE'
    || (n.tagName === 'P' && !n.textContent.trim() && n.children.length === 1 && n.firstElementChild.tagName === 'PICTURE'));

  // dark-band CTA (M4): one h2, ≤3 p, last p a lone link, nothing else
  const isCta = (nodes) => {
    const els = nodes.filter((n) => n.nodeType === 1);
    if (els.length < 2 || els.length > 4 || els[0].tagName !== 'H2') return false;
    if (!els.slice(1).every((e) => e.tagName === 'P' && !e.querySelector('picture'))) return false;
    const last = els[els.length - 1];
    const links = last.querySelectorAll('a');
    return links.length === 1 && last.textContent.trim() === links[0].textContent.trim();
  };

  sections.forEach((section, si) => {
    let style = '';
    const sm = section.querySelector(':scope > .section-metadata');
    if (sm) {
      [...sm.children].forEach((row) => {
        const [k, v] = [...row.children].map((c) => c.textContent.trim().toLowerCase());
        if (k === 'background' || k === 'style') style = v;
      });
      sm.remove();
    }
    const tone = ['dark', 'off white', 'off-white', 'light'].includes(style) ? 'light' : '';
    let nodes = [...section.childNodes].filter((n) => !isBlank(n));

    // M1 hero lead on content pages: h1 + intro p's (+ the picture that follows them)
    if (si === 0 && !isHub && nodes[0] && nodes[0].tagName === 'H1') {
      const lead = [nodes[0]];
      let picture = null;
      let i = 1;
      while (i < nodes.length && nodes[i].nodeType === 1) {
        const n = nodes[i];
        if (isPictureOnly(n)) { picture = n.tagName === 'PICTURE' ? n : n.firstElementChild; i += 1; break; }
        if (n.tagName !== 'P' || n.querySelector('picture')) break;
        lead.push(n);
        i += 1;
      }
      if (lead.length > 1 || picture) {
        const hero = el('div', 'hero');
        if (picture) {
          const r = el('div'); const c = el('div'); c.append(picture); r.append(c); hero.append(r);
        }
        const r = el('div'); const c = el('div'); c.append(...lead); r.append(c); hero.append(r);
        nodes = nodes.slice(i);
        pushSection([hero], tone);
        stats.hero = true;
      }
    }

    // one DA section per wrapper: each default-content run and each block
    let run = [];
    const flush = () => {
      if (!run.length) return;
      if (style === 'dark' && isCta(run)) {
        const cols = el('div', 'columns light');
        const r = el('div'); const c = el('div');
        c.append(...run.filter((n) => n.nodeType === 1));
        r.append(c); cols.append(r);
        stats.ctaToColumns += 1;
        stats.blocks.push('columns (light) [cta]');
        pushSection([cols], '');
      } else {
        pushSection(run, tone);
      }
      run = [];
    };
    nodes.forEach((n) => {
      if (n.nodeType === 1 && n.tagName === 'DIV' && n.className) {
        flush();
        const b = convertBlock(n);
        if (b.tagName === 'P') run.push(b); else pushSection([b], tone);
      } else {
        run.push(n);
      }
    });
    flush();
  });

  // --- metadata block (own final section)
  const md = el('div', 'metadata');
  [['Title', meta.title], ['Description', meta.desc]].forEach(([k, v]) => {
    if (!v) return;
    const r = el('div'); const a = el('div'); const b = el('div');
    a.textContent = k; b.textContent = v; r.append(a, b); md.append(r);
  });

  // --- serialize
  const ind = (n) => ' '.repeat(n);
  const sectionHtml = out.map(({ nodes, style }) => {
    const parts = nodes.map((n) => (n.nodeType === 1 ? n.outerHTML : n.textContent.trim()));
    if (style) parts.push(`<div class="section-metadata"><div><div>Style</div><div>${style}</div></div></div>`);
    return `${ind(4)}<div>\n${parts.map((p) => ind(6) + p).join('\n')}\n${ind(4)}</div>`;
  });
  sectionHtml.push(`${ind(4)}<div>\n${ind(6)}${md.outerHTML}\n${ind(4)}</div>`);
  const html = `<body>\n  <header></header>\n  <main>\n${sectionHtml.join('\n')}\n  </main>\n  <footer></footer>\n</body>\n`;
  return { html, media, stats };
}

const browser = await chromium.launch();
const page = await browser.newPage();
const manifest = new Map();
const report = [];
for (const p of pages) {
  const plain = fs.readFileSync(path.join(WORK, 'source', `${slug(p)}.plain.html`), 'utf8');
  const full = fs.readFileSync(path.join(WORK, 'source', `${slug(p)}.full.html`), 'utf8');
  const meta = headMeta(full);
  // decode entities from the head the same way the parser would
  const decoded = await page.evaluate((m) => {
    const t = document.createElement('textarea');
    t.innerHTML = m.title; const title = t.value;
    t.innerHTML = m.desc; return { title, desc: t.value };
  }, meta);
  const { html, media, stats } = await page.evaluate(transform, {
    plain,
    pagePath: p,
    isHub: HUBS.includes(p),
    meta: decoded,
    cfg: {
      host: HOST, daMedia: DA_MEDIA, facebook: FACEBOOK, facebookText: FACEBOOK_TEXT,
    },
  });
  const outFile = path.join(ROOT, 'content', `${p.replace(/^\//, '')}.html`);
  fs.mkdirSync(path.dirname(outFile), { recursive: true });
  fs.writeFileSync(outFile, html);
  media.forEach((m) => manifest.set(m.name, m));
  report.push({ path: p, file: path.relative(ROOT, outFile), ...stats });
  console.log(`${p}  imgs=${stats.images} dropped=${stats.droppedImages} hero=${stats.hero} cta=${stats.ctaToColumns} h1↓=${stats.demotedH1.length} blocks=${stats.blocks.length}`);
}
await browser.close();
fs.writeFileSync(path.join(WORK, 'media-manifest-siblings.json'), `${JSON.stringify([...manifest.values()], null, 1)}\n`);
fs.writeFileSync(path.join(WORK, 'convert-report.json'), `${JSON.stringify(report, null, 1)}\n`);
console.log(`pages=${report.length} media=${manifest.size}`);
